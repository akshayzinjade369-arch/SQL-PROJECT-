QUERIES :-


-- 1. List all crimes with victim and criminal names
SELECT C.CRIME_ID, C.CRIME_TYPE, V.VICTIM_NAME, CR.CRIMINAL_NAME
FROM CRIME C
JOIN VICTIM V ON C.VICTIM_ID = V.VICTIM_ID
JOIN CRIMINAL CR ON C.CRIMINAL_ID = CR.CRIMINAL_ID;

-- 2. Show FIR details with officer and station
SELECT F.FIR_ID, O.OFFICER_NAME, PS.STATION_NAME
FROM FIR F
JOIN OFFICER O ON F.OFFICER_ID = O.OFFICER_ID
JOIN POLICE_STATION PS ON O.STATION_ID = PS.STATION_ID;

-- 3. Case status report
SELECT CF.CASE_ID, CF.CASE_STATUS, F.FIR_ID, C.CRIME_TYPE
FROM CASE_FILE CF
JOIN FIR F ON CF.FIR_ID = F.FIR_ID
JOIN CRIME C ON F.CRIME_ID = C.CRIME_ID;

-- 4. Crimes handled by each officer
SELECT O.OFFICER_NAME, COUNT(C.CRIME_ID) AS TOTAL_CRIMES
FROM OFFICER O
LEFT JOIN CRIME C ON O.OFFICER_ID = C.OFFICER_ID
GROUP BY O.OFFICER_NAME;

-- 5. Criminals arrested by a specific station
SELECT CR.CRIMINAL_NAME, PS.STATION_NAME
FROM CRIMINAL CR
JOIN OFFICER O ON CR.ARRESTED_BY = O.OFFICER_ID
JOIN POLICE_STATION PS ON O.STATION_ID = PS.STATION_ID;

-- 6. Open cases
SELECT *
FROM CASE_FILE
WHERE CASE_STATUS = 'Open';

-- 7. Criminal count by crime level
SELECT CRIME_LEVEL, COUNT(*) AS TOTAL_CRIMINALS
FROM CRIMINAL
GROUP BY CRIME_LEVEL;

-- 8. Victims above age 25
SELECT *
FROM VICTIM
WHERE AGE > 25;

-- 9. Crimes reported in 2024
SELECT *
FROM CRIME
WHERE EXTRACT(YEAR FROM CRIME_DATE) = 2024;

-- 10. Officers working in Central Station
SELECT O.OFFICER_NAME
FROM OFFICER O
JOIN POLICE_STATION P
ON O.STATION_ID = P.STATION_ID
WHERE P.STATION_NAME = 'Central Station';

-- 11. Total FIRs registered
SELECT COUNT(*) AS TOTAL_FIRS
FROM FIR;

-- 12. Latest crime recorded
SELECT *
FROM CRIME
ORDER BY CRIME_DATE DESC;

-- 13. Number of crimes by type
SELECT CRIME_TYPE, COUNT(*) AS TOTAL
FROM CRIME
GROUP BY CRIME_TYPE;

-- 14. Officers who arrested criminals
SELECT DISTINCT O.OFFICER_NAME
FROM OFFICER O
JOIN CRIMINAL C
ON O.OFFICER_ID = C.ARRESTED_BY;

-- 15. Crime details with station name
SELECT C.CRIME_ID, C.CRIME_TYPE, P.STATION_NAME
FROM CRIME C
JOIN POLICE_STATION P
ON C.STATION_ID = P.STATION_ID;

-- 16. Closed cases
SELECT *
FROM CASE_FILE
WHERE CASE_STATUS = 'Closed';

-- 17. FIR count by officer
SELECT O.OFFICER_NAME, COUNT(F.FIR_ID) AS TOTAL_FIRS
FROM OFFICER O
LEFT JOIN FIR F
ON O.OFFICER_ID = F.OFFICER_ID
GROUP BY O.OFFICER_NAME;

-- 18. Criminals arrested by each officer
SELECT O.OFFICER_NAME, COUNT(C.CRIMINAL_ID) AS TOTAL_ARRESTS
FROM OFFICER O
LEFT JOIN CRIMINAL C
ON O.OFFICER_ID = C.ARRESTED_BY
GROUP BY O.OFFICER_NAME;

-- 19. Victim and registered officer details
SELECT V.VICTIM_NAME, O.OFFICER_NAME
FROM VICTIM V
JOIN OFFICER O
ON V.REGISTERED_BY = O.OFFICER_ID;

-- 20. Total crimes handled by station
SELECT P.STATION_NAME, COUNT(C.CRIME_ID) AS TOTAL_CRIMES
FROM POLICE_STATION P
LEFT JOIN CRIME C
ON P.STATION_ID = C.STATION_ID
GROUP BY P.STATION_NAME;

-- 21. Find all FIRs registered after a specific date
SELECT *
FROM FIR
WHERE FIR_DATE > TO_DATE('01-JAN-2024','DD-MON-YYYY');

-- 22. Show all criminals with arresting officer
SELECT C.CRIMINAL_NAME, O.OFFICER_NAME
FROM CRIMINAL C
JOIN OFFICER O
ON C.ARRESTED_BY = O.OFFICER_ID;

-- 23. Count victims registered by each officer
SELECT O.OFFICER_NAME, COUNT(V.VICTIM_ID) AS TOTAL_VICTIMS
FROM OFFICER O
LEFT JOIN VICTIM V
ON O.OFFICER_ID = V.REGISTERED_BY
GROUP BY O.OFFICER_NAME;

-- 24. Show all case files with officer details
SELECT CF.CASE_ID, CF.CASE_STATUS, O.OFFICER_NAME
FROM CASE_FILE CF
JOIN OFFICER O
ON CF.OFFICER_ID = O.OFFICER_ID;

-- 25. Display crime, victim and officer details together
SELECT C.CRIME_TYPE, V.VICTIM_NAME, O.OFFICER_NAME
FROM CRIME C
JOIN VICTIM V ON C.VICTIM_ID = V.VICTIM_ID
JOIN OFFICER O ON C.OFFICER_ID = O.OFFICER_ID;