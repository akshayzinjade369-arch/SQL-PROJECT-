CREATED TABLE :-


1) POLICE STATION 

CREATE TABLE POLICE_STATION (
    STATION_ID INT PRIMARY KEY,
    STATION_NAME VARCHAR2(50),
    LOCATION VARCHAR2(50));

2)
CREATE TABLE OFFICER (
    OFFICER_ID INT PRIMARY KEY,
    OFFICER_NAME VARCHAR2(50),
    RANK VARCHAR2(30),
    STATION_ID INT,
    FOREIGN KEY (STATION_ID) REFERENCES POLICE_STATION(STATION_ID));

3)
CREATE TABLE VICTIM (
    VICTIM_ID INT PRIMARY KEY,
    VICTIM_NAME VARCHAR2(50),
    AGE INT,
    ADDRESS VARCHAR2(100),
    REGISTERED_BY INT,
    FOREIGN KEY (REGISTERED_BY) REFERENCES OFFICER(OFFICER_ID));

4)
CREATE TABLE CRIMINAL (
    CRIMINAL_ID INT PRIMARY KEY,
    CRIMINAL_NAME VARCHAR2(50),
    CRIME_LEVEL VARCHAR2(30),
    ARRESTED_BY INT,
    FOREIGN KEY (ARRESTED_BY) REFERENCES OFFICER(OFFICER_ID));

5)
CREATE TABLE CRIME (
    CRIME_ID INT PRIMARY KEY,
    CRIME_TYPE VARCHAR2(50),
    CRIME_DATE DATE,
    VICTIM_ID INT,
    CRIMINAL_ID INT,
    OFFICER_ID INT,
    STATION_ID INT,
    FOREIGN KEY (VICTIM_ID) REFERENCES VICTIM(VICTIM_ID),
    FOREIGN KEY (CRIMINAL_ID) REFERENCES CRIMINAL(CRIMINAL_ID),
    FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER(OFFICER_ID),
    FOREIGN KEY (STATION_ID) REFERENCES POLICE_STATION(STATION_ID));

6)
CREATE TABLE FIR (
    FIR_ID INT PRIMARY KEY,
    CRIME_ID INT,
    OFFICER_ID INT,
    FIR_DATE DATE,
    FOREIGN KEY (CRIME_ID) REFERENCES CRIME(CRIME_ID),
    FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER(OFFICER_ID));

7)
CREATE TABLE CASE_FILE (
    CASE_ID INT PRIMARY KEY,
    FIR_ID INT,
    OFFICER_ID INT,
    CASE_STATUS VARCHAR2(30),
    FOREIGN KEY (FIR_ID) REFERENCES FIR(FIR_ID),
    FOREIGN KEY (OFFICER_ID) REFERENCES OFFICER(OFFICER_ID));